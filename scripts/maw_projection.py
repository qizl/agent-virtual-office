# ─── path safety (plan §4.2.3) ────────────────────────────────────────────────


def unsafe_component(path: Path) -> bool:
    """Refuse links and Windows reparse points without following their targets."""
    try:
        info = path.lstat()
    except FileNotFoundError:
        return False
    return stat.S_ISLNK(info.st_mode) or bool(
        getattr(info, "st_file_attributes", 0) & getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x400))


def _unsafe_file(message="runtime input must be a regular file without links"):
    return BridgeError("unsafe-file-type", message, EXIT_REFUSED)


def _absolute_path(path: Path) -> Path:
    # Do not resolve links before checking them, including project ancestors.
    return Path(os.path.abspath(os.fspath(path)))


def _checked_components(path: Path) -> Path:
    path = _absolute_path(path)
    current = Path(path.anchor)
    for part in path.parts[1:]:
        current /= part
        if unsafe_component(current):
            raise _unsafe_file()
    return path


def _regular(info) -> bool:
    return stat.S_ISREG(info.st_mode) and not (
        getattr(info, "st_file_attributes", 0) & getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x400))


@contextlib.contextmanager
def _windows_file_fd(path: Path):
    """Hold every directory against rename and open the leaf as a reparse point.

    Windows lacks Python's relative descriptor opens. Native directory handles
    without FILE_SHARE_DELETE/WRITE pin ancestors against rename or reparse edits.
    OPEN_REPARSE_POINT prevents following the leaf; handle and path identities
    are checked again before any bytes may leave the reader.
    """
    import ctypes
    import msvcrt
    from ctypes import wintypes

    kernel = ctypes.WinDLL("kernel32", use_last_error=True)
    create = kernel.CreateFileW
    create.argtypes = [wintypes.LPCWSTR, wintypes.DWORD, wintypes.DWORD,
                       wintypes.LPVOID, wintypes.DWORD, wintypes.DWORD, wintypes.HANDLE]
    create.restype = wintypes.HANDLE
    close = kernel.CloseHandle
    close.argtypes = [wintypes.HANDLE]
    close.restype = wintypes.BOOL
    get_info = kernel.GetFileInformationByHandle

    class HandleInfo(ctypes.Structure):
        _fields_ = [("attributes", wintypes.DWORD), ("created", wintypes.FILETIME),
                    ("accessed", wintypes.FILETIME), ("written", wintypes.FILETIME),
                    ("volume", wintypes.DWORD), ("size_high", wintypes.DWORD),
                    ("size_low", wintypes.DWORD), ("links", wintypes.DWORD),
                    ("index_high", wintypes.DWORD), ("index_low", wintypes.DWORD)]

    get_info.argtypes = [wintypes.HANDLE, ctypes.POINTER(HandleInfo)]
    get_info.restype = wintypes.BOOL
    invalid_handle = ctypes.c_void_p(-1).value
    handles = []
    identities = []
    fd = None

    def identity(handle):
        info = HandleInfo()
        if not get_info(handle, ctypes.byref(info)):
            raise ctypes.WinError(ctypes.get_last_error())
        if info.attributes & 0x400:
            raise _unsafe_file()
        return (info.volume, info.index_high, info.index_low), info.attributes

    try:
        components = [Path(path.anchor)]
        for part in path.parts[1:]:
            components.append(components[-1] / part)
        for index, component in enumerate(components):
            leaf = index == len(components) - 1
            # READ_ATTRIBUTES for dirs; GENERIC_READ for the regular leaf.
            handle = create(str(component), 0x80000000 if leaf else 0x80,
                            (0x1 | 0x2) if leaf else 0x1, None, 3,
                            0x00200000 | 0x02000000, None)
            if handle == invalid_handle:
                raise ctypes.WinError(ctypes.get_last_error())
            handles.append(handle)
            initial, attributes = identity(handle)
            if bool(attributes & 0x10) == leaf:
                raise _unsafe_file()
            identities.append((component, handle, initial))
        fd = msvcrt.open_osfhandle(handles[-1], os.O_RDONLY | os.O_BINARY)
        handles.pop()  # the Python descriptor now owns this handle
        if not _regular(os.fstat(fd)):
            raise _unsafe_file()
        yield fd
        for component, handle, initial in identities:
            current, _ = identity(handle)
            if current != initial or unsafe_component(component):
                raise _unsafe_file("runtime input identity changed during reading")
        # A no-delete-sharing handle also pins the leaf path. Compare Python's
        # native file identity to detect adapter/path changes before returning.
        current = path.lstat()
        opened = os.fstat(fd)
        if not _regular(current) or (current.st_dev, current.st_ino) != (opened.st_dev, opened.st_ino):
            raise _unsafe_file("runtime input identity changed during reading")
    finally:
        if fd is not None:
            os.close(fd)
        for handle in reversed(handles):
            close(handle)


@contextlib.contextmanager
def _regular_file_fd(path: Path):
    """Open each POSIX component relative to a pinned, non-follow directory."""
    path = _absolute_path(path)
    if os.name == "nt":
        with _windows_file_fd(path) as fd:
            yield fd
        return
    if not hasattr(os, "O_NOFOLLOW") or not hasattr(os, "O_DIRECTORY"):
        raise _unsafe_file("platform cannot safely open runtime inputs")
    fds = []
    flags = os.O_RDONLY | os.O_NOFOLLOW | getattr(os, "O_NONBLOCK", 0) | getattr(os, "O_CLOEXEC", 0)
    try:
        fds.append(os.open(path.anchor, flags | os.O_DIRECTORY))
        for part in path.parts[1:-1]:
            fds.append(os.open(part, flags | os.O_DIRECTORY, dir_fd=fds[-1]))
        fds.append(os.open(path.name, flags, dir_fd=fds[-1]))
        if not _regular(os.fstat(fds[-1])):
            raise _unsafe_file()
        yield fds[-1]
    except OSError as exc:
        if exc.errno in (errno.ELOOP, errno.ENOTDIR):
            raise _unsafe_file() from exc
        raise
    finally:
        for fd in reversed(fds):
            os.close(fd)


def read_bytes_capped(path: Path) -> bytes:
    """All content reads use one bounded, non-follow regular-file reader."""
    with _regular_file_fd(path) as fd:
        if os.fstat(fd).st_size > MAX_FILE_BYTES:
            raise OSError(errno.EFBIG, "runtime input exceeds the size limit")
        chunks = []
        remaining = MAX_FILE_BYTES + 1
        while remaining:
            chunk = os.read(fd, min(65536, remaining))
            if not chunk:
                break
            chunks.append(chunk)
            remaining -= len(chunk)
        if not remaining:
            raise OSError(errno.EFBIG, "runtime input exceeds the size limit")
        raw = b"".join(chunks)
    return raw


def _file_mtime(path: Path):
    with _regular_file_fd(path) as fd:
        return os.fstat(fd).st_mtime


def safe_resolve(root: Path, relative: str) -> Path:
    """Resolve `relative` under `root`, refusing absolute paths, traversal and
    non-regular files. Symlinks are rejected per component BEFORE resolving:
    checking after resolve() would inspect the link TARGET (a real file) and let
    a link pointing anywhere inside the project bypass the read boundary."""
    if os.path.isabs(relative) or ntpath.isabs(relative) or "\\" in relative or ".." in Path(relative).parts:
        raise BridgeError("path-outside-root", f"absolute runtime reference rejected: {relative}", EXIT_REFUSED)
    root_resolved = _checked_components(root)
    current = root_resolved
    for part in Path(relative).parts:
        current = current / part
        if unsafe_component(current):
            raise BridgeError("unsafe-file-type", f"symlink in runtime rejected: {relative}", EXIT_REFUSED)
    candidate = current
    if candidate != root_resolved and root_resolved not in candidate.parents:
        raise BridgeError("path-outside-root", f"runtime reference escapes the project root: {relative}", EXIT_REFUSED)
    if candidate.exists() and not (candidate.is_file() or candidate.is_dir()):
        raise BridgeError("unsafe-file-type", f"non-regular file in runtime: {relative}", EXIT_REFUSED)
    return candidate


def checked_path(base: Path, *parts: str) -> Path:
    """Compose base/parts and refuse symlink components or non-regular final
    files BEFORE reading. safe_resolve only guards root-relative task refs —
    every sub-read (task.json, workflow.json, role dirs, role files, listener
    state) composes BELOW it and must hold the same boundary: a symlinked
    sub-file or role directory must not turn into an out-of-project read."""
    current = _checked_components(base)
    for part in parts:
        current = current / part
        if unsafe_component(current):
            raise BridgeError("unsafe-file-type", f"symlink in runtime rejected: {current}", EXIT_REFUSED)
    if current.exists() and not (current.is_file() or current.is_dir()):
        raise BridgeError("unsafe-file-type", f"non-regular file in runtime: {current}", EXIT_REFUSED)
    return current


def read_json_capped(path: Path):
    """Return (data, degraded_reason). degraded_reason is None, 'missing',
    'corrupt' or 'unknown-schema' (schema_family, expected passed separately)."""
    try:
        raw = read_bytes_capped(path)
    except FileNotFoundError:
        return None, "missing"
    except OSError:
        return None, "corrupt"
    if len(raw) > MAX_FILE_BYTES:
        return None, "corrupt"
    try:
        return json.loads(raw.decode("utf-8")), None
    except (UnicodeDecodeError, json.JSONDecodeError):
        return None, "corrupt"


def read_json_schema(path: Path, allowed: set[str]):
    """Read a JSON object and verify its declared schema; unknown schemas degrade."""
    data, degraded = read_json_capped(path)
    if data is None:
        return None, degraded
    if not isinstance(data, dict) or data.get("schema") not in allowed:
        return None, "unknown-schema"
    return data, None


