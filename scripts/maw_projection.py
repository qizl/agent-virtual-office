def workflow_nodes(workflow: dict | None):
    """Frozen definition nodes in declaration order: [(id, type, depends_on)]."""
    if not isinstance(workflow, dict):
        return []
    definition = workflow.get("definition") or {}
    nodes = definition.get("nodes") or []
    return [(n.get("id"), n.get("type"), n.get("depends_on") or []) for n in nodes if isinstance(n, dict) and n.get("id")]


def node_states(workflow: dict | None) -> dict:
    if not isinstance(workflow, dict):
        return {}
    return workflow.get("nodes") or {}


def first_open_node(workflow: dict | None) -> tuple[str, str] | None:
    """First node not completed/released, in definition order; returns (id, status)."""
    states = node_states(workflow)
    for node_id, _node_type, _deps in workflow_nodes(workflow):
        status = (states.get(node_id) or {}).get("status")
        if status not in ("completed", "released-at-limit"):
            return node_id, status or "pending"
    return None


def effective_dev_task(tasks: list[dict]) -> dict | None:
    """Newest dev task that no later dev task supersedes (rework rounds bind by
    ref_task/logical id; a later round always wins — plan §4.3.1)."""
    dev = [t for t in tasks if t.get("type") == "dev"]
    return dev[-1] if dev else None


def effective_review_for(tasks: list[dict], dev_task: dict | None) -> dict | None:
    """Newest review task reviewing the effective dev task (exact ref_task binding;
    aggregate reviews are not broadcast across objects — plan §4.3.1)."""
    if dev_task is None:
        reviews = [t for t in tasks if t.get("type") in ("review", "aggregate-review", "plan-review")]
        return reviews[-1] if reviews else None
    dev_ref = f"{dev_task.get('_folder')}/task-{dev_task.get('seq'):03d}" if dev_task.get("_folder") else None
    reviews = []
    for t in tasks:
        if t.get("type") not in ("review", "plan-review", "aggregate-review"):
            continue
        if t.get("ref_task") in (dev_ref, None) or t.get("review_object") is not None:
            reviews.append(t)
    bound = [t for t in reviews if t.get("ref_task") == dev_ref]
    return (bound or reviews or [None])[-1]


def project_member_status(role_folder: str, role: dict, manifest_terminal: str | None, workflow: dict | None, stall_cutoff: float) -> dict:
    """Project one member's office status per the §4.3.2 mapping table."""
    tasks = role["tasks"]
    terminate = role["terminate"]
    terminate_state = (terminate or {}).get("status")
    now = time.time()

    def make(status, label, round_=None, task_kind=None, verdict=None):
        return {"status": status, "label": label, "round": round_, "task_kind": task_kind, "verdict": verdict}

    if manifest_terminal == "cancelled":
        base = make("blocked", "已取消 · 停止工作")
    elif manifest_terminal in ("completed", "completed-with-findings"):
        base = make("done", "带问题收尾" if manifest_terminal == "completed-with-findings" else "流程完成")
    else:
        base = None

    if terminate_state == "initialized":
        current = make("awaiting-approval", "等待退出确认")
    elif terminate_state == "confirmed":
        current = make("done", "已退出 🏁")
    else:
        current = None

    latest = tasks[-1] if tasks else None
    stalled = bool(latest and latest.get("status") not in ("review-passed", "review-failed")
                   and latest.get("_mtime") is not None and now - latest["_mtime"] > stall_cutoff * 60)

    if current is None and latest is not None:
        task_type = latest.get("type")
        status_value = latest.get("status")
        round_ = latest.get("round")
        kind = "review" if task_type in ("review", "plan-review", "aggregate-review") else "dev"
        if task_type == "dev":
            dev = effective_dev_task(tasks)
            if dev is not None:
                review = effective_review_for(tasks, dev)
                verdict = (review or {}).get("review") or {}
                dev_status = dev.get("status")
                if dev_status == "initialized":
                    current = make("planning", f"{dev.get('logical_work_id') or '任务'} · round {dev.get('round')}", dev.get("round"), "dev")
                elif dev_status in ("dev-complete", "reviewing"):
                    current = make("awaiting-approval", f"已交付待评审 · round {dev.get('round')}", dev.get("round"), "dev")
                elif dev_status == "review-passed":
                    current = make("done", f"✅ round {dev.get('round')} 通过", dev.get("round"), "dev", "pass")
                elif dev_status == "review-failed":
                    current = make("blocked", f"需返修 · round {dev.get('round')}", dev.get("round"), "dev", "fail")
                elif verdict.get("verdict") == "fail" and dev is not latest:
                    current = make("blocked", f"历史返修 · round {dev.get('round')}", dev.get("round"), "dev", "fail")
                else:
                    current = make("working", f"🔄 {dev.get('logical_work_id') or '实现中'} · round {dev.get('round')}", dev.get("round"), "dev")
        else:
            if status_value == "initialized":
                current = make("planning", "评审任务已派发", round_, kind)
            elif status_value == "in-progress":
                current = make("working", "🔄 评审进行中 · attempt", round_, kind)
            elif status_value in ("review-passed", "review-failed"):
                verdict = "pass" if status_value == "review-passed" else "fail"
                mark = "✅" if verdict == "pass" else "❌ 需返修"
                current = make("done", f"{mark} 评审结束 · round {round_}", round_, kind, verdict)
            else:
                current = make("working", "🔄 评审中", round_, kind)
        if stalled and current and current["status"] in ("working", "planning"):
            current = dict(current)
            current["stalled"] = True

    if base is not None:
        final = dict(base)
        if current and manifest_terminal in ("completed", "completed-with-findings"):
            # Keep the member's own exit/review outcome on top of the global terminal.
            if terminate_state == "confirmed" or (current["status"] == "done"):
                final = dict(current)
        final["round"] = current["round"] if current else None
        return final
    if current is not None:
        return current
    ready = role["ready"]
    if (ready or {}).get("status") == "confirmed":
        return make("idle", "待命")
    if (ready or {}).get("status") == "ready":
        return make("idle", "已就绪 · 待确认")
    return make("idle", None)


def project_manager(workflow: dict | None, manifest: dict, role: dict, manifest_terminal: str | None) -> dict:
    """Manager has no task files; derive from nodes + finish (plan §4.3.2)."""
    terminate = role["terminate"]
    terminate_state = (terminate or {}).get("status")

    def make(status, label):
        return {"status": status, "label": label, "round": None, "task_kind": None, "verdict": None}

    if manifest_terminal == "cancelled":
        return make("done", "流程已取消")
    if manifest_terminal == "completed-with-findings":
        return make("done", "带问题收尾")
    if manifest_terminal == "completed":
        return make("done", "流程收尾完成")
    if terminate_state == "confirmed":
        return make("done", "已退出 🏁")
    finish = (workflow or {}).get("finish") or {}
    if finish.get("terminations_published"):
        return make("awaiting-approval", "等待成员退出确认")
    if finish.get("requested") and not finish.get("evaluation"):
        return make("awaiting-approval", "等待交付评估")
    nodes = workflow_nodes(workflow)
    if not nodes:
        if workflow is None:
            return make("planning", "未提供工作流定义")
        return make("working", "🔄 推进中")
    for node_id, _type, _deps in nodes:
        state = (node_states(workflow).get(node_id) or {})
        status = state.get("status")
        if status == "running":
            blocking = state.get("blocking")
            if blocking == "finish-required":
                return make("awaiting-approval", "等待交付评估 · finish-required")
            return make("working", f"🔄 节点 {node_id} 进行中")
        if status not in ("completed", "released-at-limit"):
            return make("working", f"🔄 推进节点 {node_id}")
    if finish.get("requested"):
        return make("awaiting-approval", "等待交付评估")
    return make("working", "🔄 复核工作流")


def member_identity(state, folder):
    return hashlib.sha256(f"{state['project_root'].resolve()}|{state['task_id']}|{folder}".encode()).hexdigest()[:12]


def normalize_task_ref(value):
    if not isinstance(value, str) or len(value) > 128 or not TASK_REF_RE.fullmatch(value):
        return None
    normalized = value if value.endswith(".json") else value + ".json"
    return normalized if len(normalized) <= 128 else None


def task_identity(folder, task):
    """Expose only validated task identity, never task content or inferred links."""
    if (not isinstance(task, dict) or task.get("schema") not in tuple(TASK_SCHEMAS)
            or not _safe_integer(task.get("seq")) or task["seq"] < 1
            or not _safe_integer(task.get("round")) or task["round"] < 1
            or task.get("type") not in tuple(TASK_KINDS) or task.get("status") not in tuple(TASK_STATUSES)):
        return None
    source = normalize_task_ref(f"{folder}/task-{int(task['seq']):03d}.json")
    parent = normalize_task_ref(task.get("ref_task"))
    if source is None or (task.get("ref_task") is not None and parent is None):
        return None
    return {"seq": task["seq"], "round": task["round"], "type": task["type"],
            "source_ref": source, "ref_task": parent}


def _bound_task_records(folder, role):
    """Return task identities only when every observed filename binds its seq."""
    tasks, filenames = role["tasks"], role.get("_task_file_names")
    if not isinstance(filenames, list) or len(filenames) != len(tasks):
        return None
    records = []
    for task, filename in zip(tasks, filenames):
        identity = task_identity(folder, task)
        if identity is None or filename != identity["source_ref"].split("/", 1)[1]:
            return None
        records.append((identity, task))
    return records


def _execution_state(state):
    """Project startup from complete, bound task evidence, independently of handoffs."""
    declared = (state.get("manifest") or {}).get("roles")
    if (state.get("degraded") or state.get("_inconsistent")
            or not isinstance(declared, list) or not declared
            or any(not isinstance(folder, str) or not ROLE_FOLDER_RE.fullmatch(folder) for folder in declared)
            or len(set(declared)) != len(declared)
            or not set(declared).issubset(state["roles"])):
        return "unknown"
    started = False
    total = 0
    for folder in declared:
        if folder.rsplit("-", 1)[0] not in MEMBER_ROLES:
            continue  # Manager/workflow activity is not concrete task execution.
        records = _bound_task_records(folder, state["roles"][folder])
        if records is None:
            return "unknown"
        total += len(records)
        if total > MAX_TASK_FILES:
            return "unknown"
        for _identity, task in records:
            if task["status"] in STARTED_TASK_STATUSES:
                started = True
    return "started" if started else "not-started"


def handoff_fact(kind, sender, recipient, source, target):
    signature = f"{kind}|{sender}|{recipient}|{source}|{target}"
    identity = f"{_fnv64(signature)}{_fnv64(f'handoff:{signature}')}"
    return {"id": identity, "kind": kind, "sender_member_id": sender, "recipient_member_id": recipient,
            "source_task": source, "target_task": target}


def _fnv64(value):
    hash_value = 0xCBF29CE484222325
    for byte in value.encode("ascii"):
        hash_value = ((hash_value ^ byte) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return f"{hash_value:016x}"


def _interaction_fields(state, members):
    """Resolve exact current task relationships; no role-first recipient fallback."""
    roles = state["roles"]
    by_id = {member["id"]: member for member in members}
    records, current = {}, {}
    complete = not state["degraded"] and not state.get("_inconsistent")
    declared = (state.get("manifest") or {}).get("roles")
    declared_valid = (isinstance(declared, list) and bool(declared)
                      and all(isinstance(folder, str) and ROLE_FOLDER_RE.fullmatch(folder) for folder in declared)
                      and len(set(declared)) == len(declared))
    declared_roles = set(declared) if declared_valid else set()
    complete = complete and declared_valid and declared_roles.issubset(roles)
    total = sum(len(role["tasks"]) for role in roles.values())
    if total > MAX_TASK_FILES:
        complete = False
    for folder, role in roles.items():
        if folder not in declared_roles:
            current[folder] = None
            member = by_id.get(member_identity(state, folder))
            if member:
                member.update(current_task=None, handoff_pending=None)
            continue
        identities = _bound_task_records(folder, role)
        if identities is None:
            complete = False
            identities = []
        for identity, task in identities:
            if identity:
                if identity["source_ref"] in records:
                    complete = False
                records[identity["source_ref"]] = (folder, identity, task)
        identity = identities[-1][0] if identities else None
        current[folder] = identity
        member = by_id.get(member_identity(state, folder))
        if member:
            member.update(current_task=identity, handoff_pending=None)
    if not complete:
        for member in members:
            if member.get("current_task"):
                member["handoff_pending"] = "incomplete"
        return {"assignment_state": "unknown", "handoff_state": "unavailable", "handoffs": []}
    handoffs = []

    def available(folder):
        role = roles[folder]
        return ((role.get("ready") or {}).get("status") == "confirmed"
                and (role.get("terminate") or {}).get("status") not in ("initialized", "confirmed"))

    for folder, identity in current.items():
        if identity is None:
            continue
        member = by_id[member_identity(state, folder)]
        task = records[identity["source_ref"]][2]
        target = None
        kind = None
        if identity["type"] == "dev" and task["status"] in ("dev-complete", "reviewing"):
            matches = [record for record in records.values() if record[1]["type"] == "review"
                       and record[1]["round"] == identity["round"]
                       and record[1]["ref_task"] == identity["source_ref"]]
            if len(matches) != 1:
                member["handoff_pending"] = "conflict" if matches else "missing"
                continue
            target = matches[0]
            kind = "submission"
            if target[2]["status"] in ("review-passed", "review-failed"):
                continue
        elif identity["type"] == "review" and task["status"] in ("review-passed", "review-failed"):
            target = records.get(identity["ref_task"])
            kind = "review-result"
            if target is None:
                member["handoff_pending"] = "missing"
                continue
            if target[1]["type"] != "dev" or target[1]["round"] != identity["round"]:
                member["handoff_pending"] = "conflict"
                continue
        if target is None:
            continue
        recipient, target_identity, _target_task = target
        if recipient == folder:
            member["handoff_pending"] = "conflict"
        elif current.get(recipient) != target_identity or not available(recipient) or not available(folder):
            member["handoff_pending"] = "not-ready"
        else:
            handoffs.append(handoff_fact(kind, member["id"], member_identity(state, recipient),
                                         identity["source_ref"], target_identity["source_ref"]))
    if len(handoffs) > MAX_TASK_FILES:
        for member in members:
            if member.get("current_task"):
                member["handoff_pending"] = "incomplete"
        return {"assignment_state": "assigned" if records else "unassigned", "handoff_state": "unavailable", "handoffs": []}
    return {"assignment_state": "assigned" if records else "unassigned", "handoff_state": "complete", "handoffs": handoffs}


def disable_interactions(snapshot):
    """Disable the entire optional interaction group, retaining observed status."""
    snapshot.update(assignment_state="unknown", handoff_state="unavailable", handoffs=[])
    for member in snapshot["members"]:
        member["current_task"] = None
        member["handoff_pending"] = "incomplete"


def _display_text(value: str, maximum: int = 200) -> str:
    """Budget composed display text in JS units without splitting a surrogate pair."""
    return value.encode("utf-16-le")[:maximum * 2].decode("utf-16-le", errors="ignore")


def build_snapshot(state: dict, producer_id: str, seq: int, sampled_at: int) -> dict | None:
    manifest = state.get("manifest")
    if manifest is None:
        return None
    manifest_status = manifest.get("status")
    terminal = manifest_status if manifest_status in TERMINAL_MANIFEST else None
    workflow = state.get("workflow")
    selection = (workflow or {}).get("selection") or {}
    title = selection.get("title") or ((workflow or {}).get("definition") or {}).get("id") or ""
    active = first_open_node(workflow)
    if workflow is None or not workflow_nodes(workflow):
        # Old schemas without a frozen definition: state it, never invent a graph.
        workflow_text = "MAW（未提供工作流定义）"
    else:
        workflow_text = _display_text(f"MAW {title} · {active[0] if active else '已收尾'}")
    stall_cutoff = state.get("_stall_minutes", 30)

    members = []
    role_map = {}
    for folder, role in state["roles"].items():
        for task in role["tasks"]:
            task["_folder"] = folder
            try:
                task["_mtime"] = _file_mtime(checked_path(
                    state["project_root"] / RUNTIME_REL / state["task_id"],
                    folder, f"task-{task.get('seq'):03d}.json"))
            except OSError:
                task["_mtime"] = None
        role_map[folder] = role
    for folder in sorted(role_map):
        role_type = folder.rsplit("-", 1)[0]
        member_key = member_identity(state, folder)
        if role_type == "manager":
            projected = project_manager(workflow, manifest, role_map[folder], terminal)
        else:
            projected = project_member_status(folder, role_map[folder], terminal, workflow, stall_cutoff)
        members.append({
            "id": member_key,
            "role": role_type,
            "status": projected["status"],
            "label": projected["label"],
            "detail": None,
            "round": projected["round"],
            "task_kind": projected["task_kind"],
            "verdict": projected["verdict"],
            "terminate": ((role_map[folder].get("terminate") or {}).get("status")),
            "stalled": bool(projected.get("stalled")),
        })

    quality = "degraded" if state["degraded"] else "ok"
    quality_detail = state["degraded"][0].split(":")[0] if state["degraded"] else None
    if state.get("_inconsistent"):
        quality = "degraded"
        quality_detail = "concurrent-update"
    snapshot = {
        "schema": SCHEMA,
        "producer": producer_id,
        "seq": seq,
        "sampled_at": sampled_at,
        "workflow": workflow_text,
        "quality": quality,
        "quality_detail": quality_detail,
        "terminal": terminal,
        "execution_state": _execution_state(state),
        "members": members,
    }
    snapshot.update(_interaction_fields(state, members))
    if len(json.dumps(snapshot, ensure_ascii=False, separators=(",", ":")).encode()) > MAX_SNAPSHOT_BYTES:
        disable_interactions(snapshot)
    return snapshot


def read_with_consistency(project_root: Path, task_id: str, stall_minutes: int, *, task_validator=None) -> dict:
    """Read, fingerprint, re-read; a still-moving tree publishes concurrent-update
    degraded instead of pretending the mix is valid (plan §4.2.4)."""
    def read():
        if task_validator is None:
            return read_runtime_state(project_root, task_id)
        return read_runtime_state(project_root, task_id, task_validator=task_validator)

    state = read()
    state["_stall_minutes"] = stall_minutes
    before = fingerprint(state)
    after_state = read()
    after_state["_stall_minutes"] = stall_minutes
    after = fingerprint(after_state)
    if before != after:
        third = fingerprint(read())
        if third != after:
            after_state["_inconsistent"] = True
    return after_state



