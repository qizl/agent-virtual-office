def _plan_revision_policy_allows(workflow) -> bool:
    """Only a frozen policy that explicitly declares mutable source may enter
    the plan-revision exception; immutable, missing or unconfirmable policies
    keep the stable rejection."""
    policy = (workflow or {}).get("policy") if isinstance(workflow, dict) else None
    return isinstance(policy, dict) and policy.get("source_immutable") is False


def _revision_status_matches_blocking(blocking, status):
    if blocking == "plan-revision-in-progress":
        return status in ("initialized", "in-progress")
    if blocking == "plan-revision-review":
        return status in ("dev-complete", "reviewing")
    return blocking == "plan-review-in-progress" and status == "review-passed"


def _plan_obligation(workflow, node_id):
    obligations = (workflow or {}).get("review_obligations") if isinstance(workflow, dict) else None
    if not isinstance(obligations, dict):
        return None
    obligation = obligations.get(f"{node_id}:{PLAN_OBJECT_ID}")
    return obligation if isinstance(obligation, dict) else None


def _plan_obligation_matches(workflow, node_id, blocking) -> bool:
    """The frozen engine state must agree with the live blocking string."""
    obligation = _plan_obligation(workflow, node_id)
    if obligation is None:
        return False
    expected = "pending" if blocking == "plan-review-in-progress" else "awaiting-rework"
    return obligation.get("disposition") == expected


def _bound_records_by_ref(state: dict) -> dict | None:
    """File-bound task records only. A folder whose filenames stop binding its
    seq values hides whatever it holds — possibly a newer revision — so one
    unbound folder refuses the whole exception instead of letting older roles
    stand in for evidence that cannot be proven."""
    bound = {}
    for folder, role in state["roles"].items():
        records = _bound_task_records(folder, role)
        if records is None:
            return None
        for identity, task in records:
            bound[identity["source_ref"]] = (folder, task)
    return bound


def _obligation_attempts(obligation, key) -> list | None:
    """Engine-shaped attempt entries only: every entry carries a non-empty
    task_file and a verdict of None (published, unreviewed), "fail" or "pass".
    A malformed or impossible shape refuses the chain."""
    entries = obligation.get(key)
    if not isinstance(entries, list):
        return None
    for attempt in entries:
        if (not isinstance(attempt, dict) or type(attempt.get("task_file")) is not str
                or not attempt["task_file"]
                or attempt.get("verdict") not in (None, "fail", "pass")):
            return None
    return entries


def _plan_tail_matches(blocking, attempts) -> bool:
    """The newest published plan attempt must agree with the phase: a rework
    phase follows the failed attempt it reworks, and a running plan review
    follows that failed attempt. A passed newest attempt under an outstanding
    obligation — or any other shape — is a contradictory frozen state, and the
    rework exception never explains it."""
    if not attempts:
        return False
    if blocking == "plan-review-in-progress":
        return (attempts[-1].get("verdict") is None
                and len(attempts) >= 2 and attempts[-2].get("verdict") == "fail")
    return attempts[-1].get("verdict") == "fail"


def _internal_tail_matches(bound, internal, blocking, kind, ref, effective_ref, node_id) -> bool:
    """The engine's newest internal event must agree with the revision phase:
    an in-progress rework may only follow the failed internal attempt that
    caused it, a reviewing revision is held by its open internal review, and a
    running plan review must have been opened by the internal pass. Older
    events stay admissible history; open contradictions do not."""
    tail_ref = normalize_task_ref(internal[-1]["task_file"]) if internal else None
    if blocking == "plan-revision-in-progress":
        if kind == "review":
            return bool(internal) and internal[-1].get("verdict") == "fail" and tail_ref == ref
        return not (internal and internal[-1].get("verdict") is None)
    record = bound.get(tail_ref) if tail_ref else None
    if blocking == "plan-revision-review":
        if not internal or internal[-1].get("verdict") is not None or record is None:
            return False
        held = record[1]
        return (held.get("type") == "review" and held.get("workflow_node_id") == node_id
                and held.get("status") in ("initialized", "in-progress")
                and normalize_task_ref(held.get("ref_task")) == effective_ref)
    if kind == "review":
        if not internal or internal[-1].get("verdict") != "pass" or record is None:
            return False
        passed = record[1]
        return (passed.get("type") == "review" and passed.get("workflow_node_id") == node_id
                and passed.get("status") == "review-passed"
                and normalize_task_ref(passed.get("ref_task")) == effective_ref)
    return not (internal and internal[-1].get("verdict") is None)


def _node_revision_chain(state: dict, workflow, node_id: str, blocking: str) -> bool:
    """Engine-equivalent evidence for one plan-review node: the single newest
    (round, seq) decision-maker revision bound to the node, whose status agrees
    with the live blocking, and whose reference resolves to the engine's latest
    failed published review attempt of the SAME node — the plan review itself,
    or the internal review that failed the immediately preceding revision. The
    newest published plan attempt must agree with the phase (a rework follows
    its failure; a running plan review follows that failure), the running plan
    review must be the current published attempt, every internal hop must be a
    checkpointed failed internal attempt, and the chain must root at the
    published attempt the phase follows while the newest internal event agrees
    with the revision phase (a rework follows its failure, a reviewing revision
    holds its open review, a running plan review follows the internal pass).
    Historical chains, orphaned internal reviews and unbound file identities
    cannot substitute."""
    bound = _bound_records_by_ref(state)
    if bound is None:
        return False
    revisions = []
    for source_ref, (folder, task) in bound.items():
        if (folder.rsplit("-", 1)[0] != "decision-maker" or task.get("type") != "dev"
                or task.get("workflow_node_id") != node_id):
            continue
        revisions.append(((task.get("round") or 0, task.get("seq") or 0), source_ref, task))
    if not revisions:
        return False
    _rank, effective_ref, effective = max(revisions, key=lambda item: item[0])
    if not _revision_status_matches_blocking(blocking, effective.get("status")):
        return False
    obligation = _plan_obligation(workflow, node_id)
    if obligation is None:
        return False
    attempts = _obligation_attempts(obligation, "attempts")
    internal = _obligation_attempts(obligation, "internal_attempts")
    if attempts is None or internal is None:
        return False
    if not _plan_tail_matches(blocking, attempts):
        return False
    root_ref = normalize_task_ref(attempts[-2 if blocking == "plan-review-in-progress" else -1]["task_file"])
    if blocking == "plan-review-in-progress":
        # The running plan review audits the effective revision and must be the
        # engine's current published attempt, not an unrelated file on disk.
        running = bound.get(normalize_task_ref(attempts[-1]["task_file"]))
        if (running is None or running[1].get("type") != "plan-review"
                or running[1].get("workflow_node_id") != node_id
                or running[1].get("status") not in ("initialized", "in-progress")
                or normalize_task_ref(running[1].get("ref_task")) != effective_ref):
            return False
    ref = normalize_task_ref(effective.get("ref_task"))
    if ref is None:
        return False
    entry = bound.get(ref)
    if entry is None:
        return False
    folder, review = entry
    if review.get("status") != "review-failed" or review.get("workflow_node_id") != node_id:
        return False
    kind = review.get("type")
    if kind == "plan-review":
        # The failure that justifies this rework is the engine's latest failed
        # plan-review attempt; an older round's record cannot substitute.
        if root_ref != ref:
            return False
        if not _internal_tail_matches(bound, internal, blocking, kind, ref, effective_ref, node_id):
            return False
        return _plan_obligation_matches(workflow, node_id, blocking)
    if kind != "review":
        return False
    # The cited internal review must be a checkpointed failed internal attempt,
    # and the alternating revision/review chain must root at the published
    # plan attempt the phase follows — the rework wave it opened.
    failed_internal_refs = {normalized for attempt in internal
                            if attempt.get("verdict") == "fail"
                            for normalized in (normalize_task_ref(attempt["task_file"]),) if normalized}
    if ref not in failed_internal_refs:
        return False
    previous_ref = normalize_task_ref(review.get("ref_task"))
    previous = bound.get(previous_ref) if previous_ref else None
    if previous is None or previous[1] is effective:
        return False
    _previous_folder, previous_task = previous
    if (previous_task.get("type") != "dev" or previous_task.get("workflow_node_id") != node_id
            or previous_task.get("status") != "review-failed"):
        return False
    chain_ref, hops = normalize_task_ref(previous_task.get("ref_task")), 0
    while chain_ref != root_ref:
        if chain_ref is None or hops > len(internal):
            return False
        link = bound.get(chain_ref)
        if link is None or link[1] is effective:
            return False
        _link_folder, cited = link
        if (cited.get("type") != "review" or cited.get("status") != "review-failed"
                or cited.get("workflow_node_id") != node_id
                or chain_ref not in failed_internal_refs):
            return False
        earlier_ref = normalize_task_ref(cited.get("ref_task"))
        earlier = bound.get(earlier_ref) if earlier_ref else None
        if (earlier is None or earlier[1] is effective
                or earlier[1].get("type") != "dev"
                or earlier[1].get("workflow_node_id") != node_id
                or earlier[1].get("status") != "review-failed"):
            return False
        chain_ref = normalize_task_ref(earlier[1].get("ref_task"))
        hops += 1
    root = bound.get(root_ref)
    if (root is None or root[1].get("type") != "plan-review"
            or root[1].get("status") != "review-failed"
            or root[1].get("workflow_node_id") != node_id):
        return False
    if not _internal_tail_matches(bound, internal, blocking, kind, ref, effective_ref, node_id):
        return False
    return _plan_obligation_matches(workflow, node_id, blocking)


def plan_revision_observable(state: dict) -> bool:
    """True only when a legitimate, engine-evidenced plan revision explains the
    sole plan_ref:drifted degradation.

    Conditions that must hold together: every other input reads clean and the
    task is not terminal; the only degraded reason is plan_ref:drifted; the
    frozen policy explicitly declares mutable source; and the frozen workflow
    proves the revision — a plan-review node running with a plan-revision
    blocking whose obligation agrees, plus the single newest decision-maker
    revision bound to that node whose reference chain resolves to the engine's
    latest failed published review attempt of the same node, rooted at the
    latest failed plan attempt that opened the rework wave. A blocking string,
    an unbound file identity anywhere, a failed revision or a stale historical
    chain never qualifies; legacy tasks
    without the node binding keep the stable rejection.
    """
    if state.get("_inconsistent") or state.get("degraded") != ["plan_ref:drifted"]:
        return False
    manifest = state.get("manifest")
    if not isinstance(manifest, dict) or manifest.get("status") in TERMINAL_MANIFEST:
        return False
    workflow = state.get("workflow")
    if not _plan_revision_policy_allows(workflow):
        return False
    revision_nodes = {node_id for node_id, node_type, _deps in workflow_nodes(workflow)
                      if node_type == "plan-review"}
    if not revision_nodes:
        return False
    states = node_states(workflow)
    for node_id in revision_nodes:
        node_state = states.get(node_id) or {}
        if node_state.get("status") != "running" or node_state.get("blocking") not in PLAN_REVISION_BLOCKINGS:
            continue
        if _node_revision_chain(state, workflow, node_id, node_state["blocking"]):
            return True
    return False


def read_snapshot(project_root: Path, task_id: str, *, now=None) -> dict:
    """Read one fixed task and return the Node channel's accepted snapshot shape.

    `now` is a wall-clock millisecond value or zero-argument clock for deterministic
    callers. Envelope order is owned by the Dashboard, never by this reader.
    Missing/corrupt/inconsistent inputs fail explicitly; a legitimate plan
    revision in progress is the one bounded degradation that is served instead
    of rejected, as quality=degraded with quality_detail="plan-revision".
    """
    if not isinstance(task_id, str) or not TASK_ID_RE.fullmatch(task_id) or task_id in (".", ".."):
        raise BridgeError("invalid-task", "task identity is invalid", EXIT_USAGE)
    try:
        state = read_with_consistency(Path(project_root), task_id, 30)
        if state.get("manifest") is None:
            missing = any(reason == "task.json:missing" for reason in state["degraded"])
            raise BridgeError("task-not-found" if missing else "invalid-input", "task is unavailable" if missing else "task inputs are invalid", EXIT_NO_DATA)
        if state.get("_inconsistent"):
            raise BridgeError("input-inconsistent", "task inputs changed during observation", EXIT_NO_DATA)
        plan_revision = plan_revision_observable(state)
        if state["degraded"] and not plan_revision:
            raise BridgeError("invalid-input", "task inputs are damaged or unsupported", EXIT_NO_DATA)
        sampled_at = int((now() if callable(now) else now) if now is not None else time.time() * 1000)
        producer = "dashboard-" + hashlib.sha256(f"{Path(project_root).resolve()}|{task_id}".encode()).hexdigest()[:24]
        raw = validate_snapshot(build_snapshot(state, producer, 1, sampled_at))
        if plan_revision:
            raw["quality_detail"] = PLAN_REVISION_DETAIL
    except BridgeError:
        raise
    except (OSError, ValueError, TypeError, KeyError, AttributeError) as exc:
        raise BridgeError("read-failed", "task inputs could not be read", EXIT_NO_DATA) from exc
    snapshot = {
        "schema": raw["schema"], "workflow": raw.get("workflow"),
        "quality": raw["quality"], "quality_detail": raw.get("quality_detail"),
        "terminal": raw.get("terminal"), "sampled_at": raw["sampled_at"],
        "producer_id": raw["producer"], "producer_seq": raw["seq"],
        "accepted_at": sampled_at, "members": raw["members"],
        "execution_state": raw["execution_state"],
        "assignment_state": raw["assignment_state"], "handoff_state": raw["handoff_state"], "handoffs": raw["handoffs"],
    }
    if len(json.dumps(snapshot, ensure_ascii=False, allow_nan=False, separators=(",", ":")).encode("utf-8")) > MAX_SNAPSHOT_BYTES:
        disable_interactions(snapshot)
        if len(json.dumps(snapshot, ensure_ascii=False, allow_nan=False, separators=(",", ":")).encode("utf-8")) > MAX_SNAPSHOT_BYTES:
            raise BridgeError("payload-too-large", "snapshot exceeds the 16384 byte limit", EXIT_PROTOCOL)
    return snapshot
